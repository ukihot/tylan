export function entityTitle(entity: unknown, doc?: Doc): string {
  const e = entity as Record<string, unknown>
  if (e.itemNo) {
    return `No.${e.itemNo} ${doc?.auditTemplate.items.find((i) => i.no === e.itemNo)?.title ?? ''} · ${valueLabels[String(e.judgment)] ?? e.judgment} · ${valueLabels[String(e.scope)] ?? ''}`
  }
  return String(e.name ?? e.ssid ?? e.content ?? e.description ?? e.address ?? e.cableId ?? e.id)
}
export function draftFor<K extends Collection>(
  collection: K,
  entityId: string,
  doc: Doc,
): EntityMap[K] {
  const draft = { ...(schemaSeed(entitySchemas[collection]) as object), id: entityId } as Record<
    string,
    unknown
  >
  const values: Record<string, unknown> = {
    siteId: doc.sites[0]?.id ?? '',
    locationId: null,
    deviceId: doc.devices[0]?.id ?? '',
    portId: doc.ports[0]?.id ?? '',
    segmentId: doc.segments[0]?.id ?? '',
    roundId: doc.auditRounds.at(-1)?.id ?? '',
    siteIds: doc.sites.map((s) => s.id),
    itemNo: 1,
    serverUnknown: '配布元未確認',
    groupByLocation: true,
    viewport: { x: 0, y: 0, zoom: 1 },
  }
  for (const key of Object.keys(draft)) {
    if (key in values) {
      draft[key] = values[key]
    }
  }
  if (collection === 'links') {
    draft.a = {
      deviceId: doc.devices[0]?.id ?? '',
      portId: doc.ports.find((p) => p.deviceId === doc.devices[0]?.id)?.id ?? null,
    }
    draft.b = { unknown: '接続先未確認' }
  }
  if (collection === 'auditResults') {
    draft.scope = 'target'
    draft.targetRef = { type: 'device', id: doc.devices[0]?.id ?? '' }
  }
  return draft as EntityMap[K]
}
export function unwrap(schema: z.ZodType): z.ZodType {
  return schema instanceof z.ZodNullable || schema instanceof z.ZodOptional
    ? unwrap(schema.unwrap() as z.ZodType)
    : schema
}
